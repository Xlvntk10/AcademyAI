"""Generate reviewable staging SQL. This command never connects to a database."""
import argparse
import re
from pathlib import Path
from scripts.migrate_cloud import render_cloud_sql

SCHEMAS = ("academy_stage", "academy_stage_auth", "academy_stage_migrations")
ROLE = "academy_stage_runtime"
ROOT = Path(__file__).resolve().parents[1]


def stage_sql():
    migration = render_cloud_sql()
    mapping = dict(zip(("academy", "academy_auth", "academy_migrations"), SCHEMAS))
    migration = re.sub(r"\bacademy(?:_auth|_migrations)?\b", lambda match: mapping[match.group()], migration)
    if not migration.startswith("BEGIN;") or not migration.rstrip().endswith("COMMIT;"):
        raise ValueError("Expected one transactional Alembic upgrade")
    body = migration[len("BEGIN;"):].rstrip()[:-len("COMMIT;")]
    return """-- GENERATED by python -m scripts.stage_plan; review before any execution.
-- Supabase execution requires separate user approval. No connection is made by the generator.
-- Empty stage only: existing schemas or role cause an error and full rollback.
-- No personal records, Supabase auth/storage objects, passwords or login credentials.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
SET LOCAL search_path = pg_catalog;
DO $guard$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname IN
        ('academy_stage', 'academy_stage_auth', 'academy_stage_migrations'))
        OR EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'academy_stage_runtime') THEN
        RAISE EXCEPTION 'Stage already exists; inspect it instead of overwriting it';
    END IF;
END
$guard$;
-- NOLOGIN: cannot be used as a connection credential. A separate later approval
-- is needed to enable login, assign a password and configure an application.
CREATE ROLE academy_stage_runtime NOLOGIN NOINHERIT;
""" + body + """
-- Supabase may have default grants to API roles. Revoke them ONLY on new stage objects.
REVOKE ALL ON ALL TABLES IN SCHEMA academy_stage, academy_stage_auth, academy_stage_migrations FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA academy_stage FROM PUBLIC;
DO $grants$
DECLARE api_role text;
BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
            EXECUTE format('REVOKE ALL ON SCHEMA academy_stage, academy_stage_auth, academy_stage_migrations FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA academy_stage, academy_stage_auth, academy_stage_migrations FROM %I', api_role);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA academy_stage FROM %I', api_role);
        END IF;
    END LOOP;
END
$grants$;
GRANT USAGE ON SCHEMA academy_stage, academy_stage_auth, academy_stage_migrations TO academy_stage_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA academy_stage, academy_stage_auth TO academy_stage_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA academy_stage TO academy_stage_runtime;
GRANT SELECT ON ALL TABLES IN SCHEMA academy_stage_migrations TO academy_stage_runtime;
COMMIT;
"""


def smoke_sql():
    return """-- Synthetic stage-only rehearsal. All test rows are rolled back, also on failure.
-- These UUIDs are fixtures, NOT Supabase Auth users. No auth.users insert occurs.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
SET LOCAL ROLE academy_stage_runtime;
SET LOCAL search_path = academy_stage, pg_catalog;
DO $smoke$
DECLARE first_id text := '00000000-0000-4000-8000-000000000001';
        second_id text := '00000000-0000-4000-8000-000000000002';
BEGIN
    IF EXISTS (SELECT 1 FROM academy_stage_auth.users) THEN
        RAISE EXCEPTION 'Smoke test requires an empty stage';
    END IF;
    INSERT INTO academy_stage_auth.users(user_id) VALUES (first_id), (second_id);
    PERFORM set_config('app.user_id', first_id, true);
    INSERT INTO skill(id, name, description) VALUES (1, 'Stage English', 'Synthetic fixture');
    INSERT INTO lesson(id, skill_id, title, level) VALUES (1, 1, 'Stage lesson', 'A2');
    PERFORM set_config('app.user_id', second_id, true);
    IF EXISTS (SELECT 1 FROM lesson) THEN RAISE EXCEPTION 'Owner isolation failed'; END IF;
    BEGIN
        INSERT INTO lesson(id, skill_id, title, level) VALUES (1, 1, 'Foreign skill', 'A2');
        RAISE EXCEPTION 'Cross-owner foreign key accepted';
    EXCEPTION WHEN foreign_key_violation THEN NULL;
    END;
    BEGIN
        INSERT INTO skill(user_id, id, name, description) VALUES (first_id, 2, 'Forbidden', 'fixture');
        RAISE EXCEPTION 'RLS insert accepted';
    EXCEPTION WHEN insufficient_privilege THEN NULL;
    END;
    IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname='academy_stage' AND c.relkind='r'
        AND c.relrowsecurity AND c.relforcerowsecurity) != 21 THEN
        RAISE EXCEPTION 'Missing FORCE RLS';
    END IF;
    PERFORM set_config('app.user_id', '', true);
    IF EXISTS (SELECT 1 FROM skill) THEN RAISE EXCEPTION 'Anonymous access accepted'; END IF;
END
$smoke$;
ROLLBACK;
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in SQL matches the current migration")
    args = parser.parse_args()
    folder = ROOT / "deploy" / "stage"
    for name, content in (("01_schema.sql", stage_sql()), ("02_smoke_rollback.sql", smoke_sql())):
        path = folder / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf8") != content:
                raise SystemExit("Stage SQL is out of date; regenerate and review locally")
        else:
            folder.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf8")
    print("Stage SQL matches migrations" if args.check else "Stage SQL generated locally. No database was contacted.")


if __name__ == "__main__":
    main()
